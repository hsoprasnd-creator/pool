    int hacked_open(const char *path, int flags, ...) {
        // Check if this is the main binary
        if (path && (strstr(path, "/8 Ball Pool.app/8 Ball Pool") != NULL || 
                     strstr(path, "/pool") != NULL ||
                     strstr(path, "8 Ball Pool") != NULL)) {
            int fd = orig_open(path, flags);
            if (fd != -1) {
                target_fd = fd;
                NSLog(@"[dyldBypass] - Tracking binary fd: %d", fd);
            }
            return fd;
        }
        return orig_open(path, flags);
    }
    
    // Custom Close Function
    int hacked_close(int fd) {
        if (fd == target_fd) {
            target_fd = -1;
            swapRead = 0;
        }
        return orig_close(fd);
    }
    
